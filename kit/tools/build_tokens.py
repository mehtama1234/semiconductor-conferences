#!/usr/bin/env python3
"""Write kit/tokens.css from kit/tokens.json (the Signal Desk UX Kit tokens, copied unchanged).

The course kit uses the kit's research look: research-light, and research-dark as the dark theme.
Run: python3 kit/tools/build_tokens.py
"""
import json, re
from pathlib import Path
KIT = Path(__file__).resolve().parent.parent
T = json.loads((KIT / "tokens.json").read_text())

def theme(tid):
    raw = {t["name"]: t["value"].get(tid) for t in T["color"]["tokens"] if t["value"].get(tid)}
    def res(v, depth=0):
        m = re.fullmatch(r"\{(.+)\}", v)
        return res(raw[m.group(1)], depth + 1) if m and depth < 5 else v
    return {k: res(v) for k, v in raw.items()}

def decl(d):
    return "".join(f"--{k}:{v};" for k, v in d.items())

light, dark = theme("research-light"), theme("research-dark")
# Tokens the dark theme does not define keep their light value.
dark_only = {k: v for k, v in dark.items() if light.get(k) != v}
fam = T["type"]["families"]
rest = {"font-display": fam["display"], "font-body": fam["body"], "font-label": fam["label"]}
for grp in ("spacing", "radius", "stroke", "layout"):
    for t in T[grp]["tokens"]:
        rest[t["name"]] = t["value"]
# Extras the boards use on the espresso band and are not in tokens.json (values from as.css).
extras_light = {"espresso-rule": "#6f5d4f", "card-shadow": "0 0 0 transparent"}
FONTS = [
 ("Fraunces", "normal", "100 900", "fraunces-latin-wght-normal", "U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD"),
 ("Fraunces", "italic", "100 900", "fraunces-latin-wght-italic", None),
 ("Fraunces", "normal", "100 900", "fraunces-latin-ext-wght-normal", "U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C4,U+2113,U+2C60-2C7F,U+A720-A7FF"),
 ("Fraunces", "italic", "100 900", "fraunces-latin-ext-wght-italic", None),
 ("Source Serif 4", "normal", "200 900", "source-serif-4-latin-wght-normal", None),
 ("Source Serif 4", "italic", "200 900", "source-serif-4-latin-wght-italic", None),
 ("Source Serif 4", "normal", "200 900", "source-serif-4-latin-ext-wght-normal", None),
 ("Source Serif 4", "italic", "200 900", "source-serif-4-latin-ext-wght-italic", None),
 ("Source Serif 4", "normal", "200 900", "source-serif-4-greek-wght-normal", "U+0370-0377,U+037A-037F,U+0384-038A,U+038C,U+038E-03A1,U+03A3-03FF"),
 ("Source Serif 4", "italic", "200 900", "source-serif-4-greek-wght-italic", None),
 ("IBM Plex Sans Condensed", "normal", "500", "ibm-plex-sans-condensed-latin-500-normal", None),
 ("IBM Plex Sans Condensed", "normal", "600", "ibm-plex-sans-condensed-latin-600-normal", None),
 ("IBM Plex Sans Condensed", "normal", "500", "ibm-plex-sans-condensed-latin-ext-500-normal", None),
 ("IBM Plex Sans Condensed", "normal", "600", "ibm-plex-sans-condensed-latin-ext-600-normal", None),
]
LATIN, EXT = FONTS[0][4], FONTS[2][4]
out = ["/* Generated by tools/build_tokens.py from tokens.json (Signal Desk UX Kit, version %s). Do not edit by hand.\n   Light = research-light. Dark = research-dark. */" % T["version"]]
for fam_, style, weight, file, rng in FONTS:
    rng = rng or (EXT if "-ext-" in file else LATIN)
    out.append(f"@font-face{{font-family:'{fam_}';font-style:{style};font-weight:{weight};font-display:swap;src:url(fonts/{file}.woff2) format('woff2');unicode-range:{rng}}}")
out.append(":root{color-scheme:light;" + decl(light) + decl(extras_light) + decl(rest) + "}")
d = "color-scheme:dark;" + decl(dark_only)
out.append("@media (prefers-color-scheme:dark){:root:not([data-theme=\"light\"]){" + d + "}}")
out.append(":root[data-theme=\"dark\"]{" + d + "}")
(KIT / "tokens.css").write_text("\n".join(out) + "\n")
print("tokens.css", len(light), "light,", len(dark_only), "dark overrides")
