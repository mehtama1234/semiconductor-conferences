#!/usr/bin/env python3
"""Write kit/slides.css from boards/slides.css (the presentation boards' own slide stylesheet, copied unchanged).
Every rule is scoped under .slide, the body rule is dropped, and hex colours become tokens so the light slide follows
the page theme. The dark slide (.slide.dark) stays espresso in both themes, as on the boards.
Run: python3 kit/tools/port_slide_css.py"""
import re
from pathlib import Path
KIT = Path(__file__).resolve().parent.parent
src = re.sub(r"/\*.*?\*/", "", (KIT / "boards" / "slides.css").read_text(), flags=re.S)
BG = {"#f3ede2": "page", "#fbf7f0": "paper", "#3a2e26": "espresso", "#ece4d5": "sand", "#f5e6d3": "peach-soft", "#f4e1d8": "hold-wash", "#9a4a22": "rust", "#e3b98f": "peach"}
FG = {"#2b2622": "ink", "#5a5047": "muted", "#9a4a22": "rust", "#6e3214": "rust-dark", "#8b2e1f": "hold", "#d9cdba": "line", "#8f7d69": "line-strong", "#3a2e26": "mark-1",
      "#f3ede2": "on-espresso", "#e5dacb": "on-espresso-muted", "#e3b98f": "peach", "#fbf6ee": "on-rust", "#fbf7f0": "paper", "#6f5d4f": "espresso-rule", "#b8a58e": "line-strong"}
out = []
for sel, body in re.findall(r"([^{}]+)\{([^{}]*)\}", src):
    sel = sel.strip()
    if sel == "body": continue
    dark = ".slide.dark" in sel or sel in (".band", ".band b", ".bul", ".t-ve")
    decls = []
    for d in body.split(";"):
        if not d.strip(): continue
        prop = d.split(":", 1)[0].strip()
        def sub(m, prop=prop):
            h = m.group(0).lower()
            if dark and h in ("#3a2e26", "#f3ede2", "#e3b98f", "#e5dacb"): return {"#3a2e26": "var(--espresso)", "#f3ede2": "var(--on-espresso)", "#e3b98f": "var(--peach)", "#e5dacb": "var(--on-espresso-muted)"}[h]
            t = (BG if prop.startswith("background") else FG).get(h) or FG.get(h) or BG.get(h)
            return f"var(--{t})" if t else m.group(0)
        decls.append(re.sub(r"#[0-9a-fA-F]{6}\b", sub, d))
    sels = []
    for s in sel.split(","):
        s = s.strip()
        sels.append(s if s.startswith(".slide") else ".slide " + s)
    out.append(",".join(sels) + "{" + ";".join(decls) + "}")
css = "\n".join(out)
# the dark slide keeps light-on-dark text whatever the page theme; its paper cards keep ink text
css += "\n.slide.dark .cc,.slide.dark .card,.slide.dark .media{background:#fbf7f0;color:#2b2622}\n.slide.dark .cc .m,.slide.dark .card .m{color:#5a5047}.slide.dark .cc .lab,.slide.dark .card .lab{color:#9a4a22}\n.slide.dark .cc .t,.slide.dark .card .t{color:#2b2622;border-color:#2b2622;background:#fbf7f0}\n.slide .huge{margin:0;font:400 260px/.9 Fraunces,Georgia,serif;letter-spacing:-.03em;color:var(--ink);font-variant-numeric:lining-nums}\n.slide .ans strong{color:var(--rust);font-weight:600}\n.slide .q{margin:0;font:italic 400 64px/1.18 Fraunces,Georgia,serif;letter-spacing:-.01em;max-width:1500px}\n.slide .q em{color:var(--rust)}.slide.dark .q em{color:var(--peach)}\n.slide .vs{display:grid;grid-template-columns:minmax(0,1fr) 80px minmax(0,1fr);gap:0;align-items:stretch}\n.slide .vs>i{align-self:center;justify-self:center;font:italic 400 44px/1 Fraunces,Georgia,serif;color:var(--rust)}\n"
(KIT / "slides.css").write_text("/* Generated by tools/port_slide_css.py from boards/slides.css (Sense to Silicon presentation boards). Rules are the boards'. */\n" + css)
print("slides.css written;", len(out), "rules; hex left:", sorted(set(re.findall(r"#[0-9a-fA-F]{6}\b", css))))
