#!/usr/bin/env python3
"""Write kit/boards.css: the canvas's own stylesheet (boards/as.css, copied unchanged) with every
hex colour replaced by the matching token, so the same rules work in the dark theme.
Nothing else is changed: selectors, sizes, spacing, type and borders are the boards'.
course.css then adds the fluid layout and the course components on top.
Run: python3 kit/tools/port_board_css.py
"""
import re
from pathlib import Path
KIT = Path(__file__).resolve().parent.parent
src = (KIT / "boards" / "as.css").read_text()

BG = {"#f3ede2": "page", "#fbf7f0": "paper", "#3a2e26": "espresso", "#fff8ee": "paper", "#2b2622": "espresso", "#5a4a3e": "espresso-rule"}
FG = {"#f3ede2": "on-espresso", "#fbf7f0": "on-espresso", "#fff": "on-rust", "#fbf6ee": "on-rust", "#3a2e26": "mark-1",
      "#2b2622": "ink"}
ANY = {"#5a5047": "muted", "#9a4a22": "rust", "#6e3214": "rust-dark", "#e3b98f": "peach", "#ece4d5": "sand",
       "#d9cdba": "line", "#8f7d69": "line-strong", "#b9ab98": "line-strong", "#f5e6d3": "peach-soft",
       "#8b2e1f": "hold", "#f4e1d8": "hold-wash", "#d9a894": "hold", "#e5dacb": "on-espresso-muted",
       "#d8c9b5": "on-espresso-muted", "#e8dccb": "on-espresso-muted", "#d0c0aa": "on-espresso-muted",
       "#e0d3c1": "on-espresso-muted", "#c9b8a2": "on-espresso-muted", "#6f5d4f": "espresso-rule",
       "#4a4038": "muted", "#3a322c": "ink"}
HEX = re.compile(r"#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b")

def port_decl(decl, on_dark):
    prop = decl.split(":", 1)[0].strip().lower()
    is_bg = prop.startswith("background")
    def sub(m):
        h = m.group(0).lower()
        if h in ANY: return f"var(--{ANY[h]})"
        if is_bg and h in BG: return f"var(--{BG[h]})"
        if h == "#2b2622" and on_dark: return "var(--espresso-deep,#2b2622)"
        if h in FG: return f"var(--{FG[h]})"
        return m.group(0)
    return HEX.sub(sub, decl)

out = []
for rule in re.finditer(r"(/\*.*?\*/)|([^{}]+)\{([^{}]*)\}", src, flags=re.S):
    if rule.group(1):
        out.append(rule.group(1)); continue
    sel, body = rule.group(2).strip(), rule.group(3)
    decls = [d for d in body.split(";") if d.strip()]
    # light-on-dark blocks: a paper/page background on the espresso band stays a light chip
    out.append(sel + "{" + ";".join(port_decl(d, False) for d in decls) + "}")
css = "\n".join(out)
# the two rules that hard-code the artboard: let the page set width instead
css = css.replace(".root{box-sizing:border-box;width:1440px;", ".root{box-sizing:border-box;max-width:1440px;margin:0 auto;")
css = css.replace(".root.phone{width:390px;", ".root.phone{max-width:390px;")
head = "/* Generated by tools/port_board_css.py from boards/as.css (Atom to Answer canvas; its header says the\n   style is copied from the Sense to Silicon chip boards). Rules are the boards'; colours are tokens. */\n"
(KIT / "boards.css").write_text(head + css + "\n")
left = sorted(set(m.group(0) for m in HEX.finditer(css)))
print("boards.css written;", len(out), "rules; hex left:", left)
